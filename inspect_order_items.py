
import pandas as pd

# Load Order Items dataset
items = pd.read_csv("data/raw/olist_order_items_dataset.csv")

# Display first 5 records
print(items.head())

# Display dataset information
print(items.info())

# Display statistical summary
print(items.describe(include="all"))

# 1. Check duplicate rows
print("Duplicate rows:", items.duplicated().sum())

# 2. Check duplicate order-item combinations
print(
    "Duplicate order-item combinations:",
    items.duplicated(
        subset=["order_id", "order_item_id"]
    ).sum()
)

# 3. Check number of unique orders
print("Unique orders:", items["order_id"].nunique())

# 4. Check number of unique products
print("Unique products:", items["product_id"].nunique())

# 5. Check number of unique sellers
print("Unique sellers:", items["seller_id"].nunique())









































































































































































































































































































































































































































































































































































